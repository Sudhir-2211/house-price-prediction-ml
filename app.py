import os
import json
import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
from src.predict import predict_price

# Page Configuration
st.set_page_config(
    page_title="House Price ML Estimator | Sudhir Kumar",
    page_icon="🏡",
    layout="wide",
    initial_sidebar_state="expanded",
)

# Custom Styling
st.markdown(
    """
    <style>
    .main-header {
        font-size: 2.2rem;
        font-weight: 700;
        color: #1E3A8A;
        margin-bottom: 0.2rem;
    }
    .sub-header {
        font-size: 1rem;
        color: #4B5563;
        margin-bottom: 1.2rem;
    }
    .disclaimer-box {
        background-color: #FEF3C7;
        border-left: 5px solid #F59E0B;
        padding: 12px 16px;
        border-radius: 4px;
        margin-bottom: 1.5rem;
        color: #92400E;
        font-size: 0.92rem;
    }
    </style>
    """,
    unsafe_allow_html=True,
)

st.markdown('<div class="main-header">🏡 House Price Valuation & ML Estimation Pipeline</div>', unsafe_allow_html=True)
st.markdown(
    '<div class="sub-header">Supervised regression pipeline comparing Ridge Regression, Random Forests, and Gradient Boosting for residential property valuation.</div>',
    unsafe_allow_html=True,
)

# Mandatory Domain Disclaimer
st.markdown(
    """
    <div class="disclaimer-box">
        <strong>⚠️ IMPORTANT VALUATION DISCLAIMER:</strong> Predictions generated by this machine learning model are statistical point estimates intended solely for educational demonstration and academic portfolio review. They do <strong>not</strong> constitute an official real estate appraisal, mortgage underwriting document, or formal commercial valuation. Real-world values depend on hyper-local zoning, recent neighborhood comps, interior finishes, and licensed appraiser inspections.
    </div>
    """,
    unsafe_allow_html=True,
)

base_dir = os.path.dirname(os.path.abspath(__file__))
metrics_file = os.path.join(base_dir, "models", "model_metrics.json")
metrics_data = {}
if os.path.exists(metrics_file):
    with open(metrics_file, "r") as f:
        metrics_data = json.load(f)

# Sidebar: Property Feature Inputs
st.sidebar.header("📐 Property Parameters")

sqft = st.sidebar.slider("Living Area (sq ft)", min_value=700, max_value=5500, value=2200, step=50)
location = st.sidebar.selectbox("Location Tier", ["Urban Prime", "Suburban Central", "Outer Suburban", "Rural Scenic"], index=1)
beds = st.sidebar.slider("Bedrooms", min_value=1, max_value=6, value=3)
baths = st.sidebar.slider("Bathrooms", min_value=1.0, max_value=5.0, value=2.5, step=0.5)
year = st.sidebar.slider("Year Built", min_value=1950, max_value=2024, value=2008)
lot_acres = st.sidebar.slider("Lot Size (Acres)", min_value=0.05, max_value=3.0, value=0.25, step=0.05)
garage = st.sidebar.selectbox("Garage Spaces", [0, 1, 2, 3], index=2)
condition = st.sidebar.select_slider("Condition Rating", options=[1, 2, 3, 4, 5], value=4)
pool = st.sidebar.checkbox("Has Inground Swimming Pool", value=False)

tab_pred, tab_models, tab_dataset = st.tabs(["🎯 Valuation Estimation", "📊 Model Comparison & Metrics", "📋 Dataset Overview"])

with tab_pred:
    st.subheader("Statistical Price Estimation")
    try:
        res = predict_price(
            sqft_living=sqft,
            bedrooms=beds,
            bathrooms=baths,
            location_tier=location,
            year_built=year,
            lot_size_acres=lot_acres,
            garage_spaces=garage,
            condition_rating=condition,
            has_pool=1 if pool else 0,
        )

        col_est1, col_est2, col_est3 = st.columns(3)
        with col_est1:
            st.metric("Estimated Market Price", f"${res['estimated_price']:,.0f}")
        with col_est2:
            st.metric("90% Lower Bound", f"${res['confidence_lower']:,.0f}")
        with col_est3:
            st.metric("90% Upper Bound", f"${res['confidence_upper']:,.0f}")

        # Gauge Chart for Price Position
        fig_gauge = go.Figure(go.Indicator(
            mode="gauge+number",
            value=res["estimated_price"],
            domain={'x': [0, 1], 'y': [0, 1]},
            title={'text': "Market Valuation Index ($)", 'font': {'size': 18}},
            number={'valueformat': "$,.0f"},
            gauge={
                'axis': {'range': [100000, 1500000]},
                'bar': {'color': "#1E3A8A"},
                'steps': [
                    {'range': [100000, 400000], 'color': "#E2E8F0"},
                    {'range': [400000, 800000], 'color': "#CBD5E1"},
                    {'range': [800000, 1500000], 'color': "#94A3B8"},
                ],
                'threshold': {
                    'line': {'color': "#E11D48", 'width': 4},
                    'thickness': 0.75,
                    'value': res["estimated_price"],
                }
            }
        ))
        fig_gauge.update_layout(height=280, margin=dict(t=30, b=10, l=30, r=30))
        st.plotly_chart(fig_gauge, use_container_width=True)

        st.write("#### 🔍 Key Valuation Drivers")
        drivers = [
            {"Factor": "Square Footage", "Value": f"{sqft:,} sq ft", "Impact": "Primary positive pricing driver (~$185/sq ft)"},
            {"Factor": "Location", "Value": location, "Impact": "Zonal premium tier adjustment (up to +45% in Urban Prime)"},
            {"Factor": "Year Built", "Value": f"{year}", "Impact": "Modern plumbing, insulation, and building code premium"},
            {"Factor": "Condition", "Value": f"{condition} / 5", "Impact": "Renovation and maintenance differential"},
            {"Factor": "Pool & Amenities", "Value": "Yes" if pool else "No", "Impact": "Luxury amenity valuation bump"},
        ]
        st.table(pd.DataFrame(drivers))

    except Exception as ex:
        st.error(f"Error executing prediction: {ex}")

with tab_models:
    st.subheader("Model Benchmark & Cross-Validation Results")
    if "comparison" in metrics_data:
        comp_rows = []
        for m_name, m_vals in metrics_data["comparison"].items():
            comp_rows.append({
                "Model Architecture": m_name,
                "R² Score": m_vals["R2_Score"],
                "MAE ($)": f"${m_vals['MAE']:,.2f}",
                "RMSE ($)": f"${m_vals['RMSE']:,.2f}",
                "MAPE (%)": f"{m_vals['MAPE_pct']:.2f}%",
            })
        st.dataframe(pd.DataFrame(comp_rows), use_container_width=True)
        st.success(f"Production Model Selected: **{metrics_data.get('best_model', 'Gradient Boosting')}** based on highest coefficient of determination ($R^2$).")
    else:
        st.info("Train the model using 'python -m src.train' to view benchmark comparisons.")

with tab_dataset:
    st.subheader("Benchmark Training Dataset")
    data_path = os.path.join(base_dir, "data", "house_prices.csv")
    if os.path.exists(data_path):
        raw_df = pd.read_csv(data_path)
        st.dataframe(raw_df.head(20), use_container_width=True)
        st.caption(f"Dataset contains {len(raw_df):,} verified property transactions with 10 features.")
    else:
        st.warning("Dataset file not found.")
